#!/usr/bin/env bash
# ABOUTME: Fixture test for strip-carnet-footer.sh — a stubbed gh serves footered and clean entries
# ABOUTME: and proves which ones are edited, what the edit leaves, and that each failure shape fails the run
#
# SPDX-License-Identifier: MIT OR Apache-2.0
# Copyright (c) 2026 dravr.ai
#
# The sweep edits a private tracker from a cron lane, so this test is its only
# check before it meets real comments. carnet.sh's own footer test was green
# while the footer kept landing, because it read the body the script sent, not
# the one GitHub stored; here the stub answers each PATCH with a stored body,
# and the case where that body still carries the footer must fail the run.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UNDER_TEST="$SCRIPT_DIR/strip-carnet-footer.sh"

failures=0
pass() { echo "  ✅ $1"; }
fail() { echo "  ❌ $1"; failures=$((failures + 1)); }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
OUT="$WORK/out"
LOG="$WORK/patches"

FOOTER=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
ROBOT=$'\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'
MARKER='<!-- carnet-release {"v":2,"reason":"landed\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"} -->'

# Comments: a trailing footer, a footer inside a marker's JSON, the robot
# wording, and a clean one that must be left alone. Issues: one footered body.
jq -n --arg f "$FOOTER" --arg r "$ROBOT" --arg m "$MARKER" '[
  {id: 1, body: ("where / what / fix" + $f)},
  {id: 2, body: ($m + "\n🔓 Released")},
  {id: 3, body: ("closed" + $r)},
  {id: 4, body: "a plain comment\n\n---\nwith a rule of its own\n"}
]' > "$WORK/comments.json"
jq -n --arg f "$FOOTER" '[{number: 77, body: ("the issue body" + $f)}, {number: 78, body: null}]' \
    > "$WORK/issues.json"

mkdir -p "$WORK/bin"
cat > "$WORK/bin/gh" <<'STUB'
#!/usr/bin/env bash
# Serves the fixtures for GETs; for a PATCH, logs the endpoint and payload and
# answers with the stored body — re-signed when STUB_RESIGN is set.
set -euo pipefail
[ "$1" = api ] && shift
if [ "${1:-}" = "-X" ] && [ "$2" = PATCH ]; then
  path=$3 input=$5
  body=$(jq -r .body "$input")
  printf '%s\t%s\n' "$path" "$(jq -c .body "$input")" >> "$STUB_LOG"
  [ -n "${STUB_FAIL:-}" ] && exit 1
  [ -n "${STUB_RESIGN:-}" ] && body="$body"$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
  jq -n --arg b "$body" '{body: $b}'
  exit 0
fi
case "$*" in
  *issues/comments\?*) cat "$STUB_DIR/comments.json" ;;
  *issues\?*) cat "$STUB_DIR/issues.json" ;;
  *) echo "unexpected gh call: $*" >&2; exit 3 ;;
esac
STUB
chmod +x "$WORK/bin/gh"

run_sweep() { # extra env as KEY=VAL... then -- args; echoes the exit code
  local code=0 envs=()
  while [ $# -gt 0 ] && [ "$1" != -- ]; do envs+=("$1"); shift; done
  [ "${1:-}" = -- ] && shift
  : > "$LOG"
  env PATH="$WORK/bin:$PATH" STUB_DIR="$WORK" STUB_LOG="$LOG" GH_TOKEN=test "${envs[@]}" \
      "$UNDER_TEST" --since 2026-10-20T00:00:00Z "$@" > "$OUT" 2>&1 || code=$?
  printf '%s\n' "$code"
}

stored() { awk -F'\t' -v p="$1" '$1 == p { print $2 }' "$LOG" | jq -r .; }

echo "strip-carnet-footer.sh"

code=$(run_sweep --)
[ "$code" = 0 ] && pass "a clean sweep exits 0" || { fail "a clean sweep exits 0 (exit $code)"; cat "$OUT"; }
[ "$(wc -l < "$LOG" | tr -d ' ')" = 4 ] && pass "edits exactly the four footered entries" \
    || { fail "edits exactly the four footered entries"; cat "$LOG"; }
grep -q 'issues/comments/4' "$LOG" && fail "leaves a clean comment with its own --- rule alone" \
    || pass "leaves a clean comment with its own --- rule alone"
[ "$(stored repos/dravr-ai/dravr-carnet/issues/comments/1)" = "where / what / fix" ] \
    && pass "drops the footer, its rule and the blank lines before it" \
    || fail "drops the footer, its rule and the blank lines before it: $(stored repos/dravr-ai/dravr-carnet/issues/comments/1)"
marker=$(stored repos/dravr-ai/dravr-carnet/issues/comments/2)
json=$(sed -n 's/^<!-- carnet-release \(.*\) -->$/\1/p' <<<"$marker")
[ "$(jq -r .reason <<<"$json" 2>/dev/null)" = landed ] \
    && pass "strips the escaped footer inside a marker and keeps its JSON valid" \
    || fail "strips the escaped footer inside a marker and keeps its JSON valid: $marker"
[ "$(stored repos/dravr-ai/dravr-carnet/issues/comments/3)" = closed ] \
    && pass "strips the robot 'Generated with' wording" \
    || fail "strips the robot 'Generated with' wording"
[ "$(stored repos/dravr-ai/dravr-carnet/issues/77)" = "the issue body" ] \
    && pass "strips an issue body through issues/<n>" || fail "strips an issue body through issues/<n>"
grep -q '4 entries carried the footer, 4 edited, 0 failed' "$OUT" \
    && pass "prints only counts" || { fail "prints only counts"; cat "$OUT"; }
grep -q 'where / what' "$OUT" && fail "never prints a body" || pass "never prints a body"

code=$(run_sweep -- --dry-run)
[ "$code" = 0 ] && [ ! -s "$LOG" ] && grep -q '4 entries carried the footer, 0 edited' "$OUT" \
    && pass "--dry-run counts and edits nothing" || { fail "--dry-run counts and edits nothing"; cat "$OUT"; }

code=$(run_sweep STUB_RESIGN=1 --)
[ "$code" = 1 ] && grep -q 're-appends it' "$OUT" \
    && pass "fails when the stored body still carries the footer" \
    || { fail "fails when the stored body still carries the footer (exit $code)"; cat "$OUT"; }

code=$(run_sweep STUB_FAIL=1 --)
[ "$code" = 1 ] && grep -q '4 failed' "$OUT" \
    && pass "fails when an edit is refused" || { fail "fails when an edit is refused (exit $code)"; cat "$OUT"; }

code=$(run_sweep GH_TOKEN= --)
[ "$code" = 1 ] && grep -q 'GH_TOKEN is empty' "$OUT" \
    && pass "an empty token fails instead of sweeping nothing" \
    || { fail "an empty token fails instead of sweeping nothing (exit $code)"; cat "$OUT"; }

if [ "$failures" -gt 0 ]; then
    echo "❌ $failures check(s) failed"
    exit 1
fi
echo "✅ all checks passed"
